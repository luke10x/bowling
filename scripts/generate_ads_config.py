#!/usr/bin/env python3
"""Generate the iOS and H5 adapters from the C++ ad configuration."""

from pathlib import Path
import argparse
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / "ads_config.h"
IOS_OUTPUT = ROOT / "ios-project/generated_ads.xcconfig"
WEB_OUTPUT = ROOT / "wasm/ads_config.js"
ADS_TXT_OUTPUT = ROOT / "wasm/ads.txt"

STRINGS = (
    "ANDROID_APP_ID", "ANDROID_INTERSTITIAL_ID", "ANDROID_REWARDED_ID",
    "IOS_APP_ID", "IOS_INTERSTITIAL_ID", "IOS_REWARDED_ID",
    "TEST_ANDROID_APP_ID", "TEST_ANDROID_INTERSTITIAL_ID", "TEST_ANDROID_REWARDED_ID",
    "TEST_IOS_APP_ID", "TEST_IOS_INTERSTITIAL_ID", "TEST_IOS_REWARDED_ID",
    "H5_PUBLISHER_ID",
)
NUMBERS = ("H5_FREQUENCY_HINT_SECONDS", "H5_LOCAL_TEST_MODE",
           "H5_HOUSE_PROMO_WHILE_PENDING", "MONEY_REWARD")


def read_config():
    values = {}
    for name, value in re.findall(r'^#define ADS_([A-Z0-9_]+)\s+("[^"]*"|[0-9]+)\s*$',
                                  HEADER.read_text(), re.M):
        if name in values:
            raise ValueError(f"duplicate ADS_{name}")
        values[name] = value.strip('"')
    missing = set(STRINGS + NUMBERS) - values.keys()
    if missing:
        raise ValueError(f"missing values in {HEADER}: {', '.join(sorted(missing))}")
    for name in STRINGS:
        if not re.fullmatch(r'[A-Za-z0-9~./-]+', values[name]):
            raise ValueError(f"unsafe string value for ADS_{name}")
    if values["H5_LOCAL_TEST_MODE"] not in ("0", "1"):
        raise ValueError("ADS_H5_LOCAL_TEST_MODE must be 0 or 1")
    if values["H5_HOUSE_PROMO_WHILE_PENDING"] not in ("0", "1"):
        raise ValueError("ADS_H5_HOUSE_PROMO_WHILE_PENDING must be 0 or 1")
    if not re.fullmatch(r"ca-pub-[0-9]{16}", values["H5_PUBLISHER_ID"]):
        raise ValueError("ADS_H5_PUBLISHER_ID must be an AdSense ca-pub ID")
    return values


def generated_files(values):
    ios = ["// Generated by scripts/generate_ads_config.py from ads_config.h. Do not edit."]
    for prefix in ("IOS", "TEST_IOS"):
        for kind in ("APP_ID", "INTERSTITIAL_ID", "REWARDED_ID"):
            ios.append(f"ADS_{prefix}_{kind} = {values[prefix + '_' + kind]}")
    web = [
        "// Generated by scripts/generate_ads_config.py from ads_config.h. Do not edit.",
        f'window.BOWLING_ADSENSE_CLIENT = "{values["H5_PUBLISHER_ID"]}";',
        f'window.BOWLING_AD_FREQUENCY_HINT = "{values["H5_FREQUENCY_HINT_SECONDS"]}s";',
        f'window.BOWLING_MONEY_REWARD = {values["MONEY_REWARD"]};',
        f'window.BOWLING_H5_HOUSE_PROMO = {"true" if values["H5_HOUSE_PROMO_WHILE_PENDING"] == "1" else "false"};',
        "// Loopback uses the local preview; public hosts use the selected live mode.",
        (r"window.BOWLING_ADS_TEST = /^(localhost|127\.0\.0\.1|\[::1\])$/.test(window.location.hostname);"
         if values["H5_LOCAL_TEST_MODE"] == "1" else "window.BOWLING_ADS_TEST = false;"),
    ]
    ads_txt = ("google.com, " + values["H5_PUBLISHER_ID"].removeprefix("ca-") +
               ", DIRECT, f08c47fec0942fa0\n")
    return {IOS_OUTPUT: "\n".join(ios) + "\n",
            WEB_OUTPUT: "\n".join(web) + "\n",
            ADS_TXT_OUTPUT: ads_txt}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated adapters are stale")
    args = parser.parse_args()
    stale = []
    for path, content in generated_files(read_config()).items():
        if not path.exists() or path.read_text() != content:
            stale.append(path)
            if not args.check:
                path.write_text(content)
    if stale and args.check:
        print("Stale ad adapters: " + ", ".join(str(p.relative_to(ROOT)) for p in stale), file=sys.stderr)
        return 1
    if not args.check:
        print("Ad adapters synchronized from ads_config.h")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
